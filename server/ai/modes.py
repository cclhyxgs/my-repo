def get_mode(name: str) -> dict:
    """取模式配置；未知模式返回空字典（调用方需自行兜底）。"""
    return TASK_MODES.get(name) or {}


def forbidden_of(name: str) -> list:
    return list(get_mode(name).get("forbidden") or [])


def temperature_of(name: str, default: float = 0.4) -> float:
    return float(get_mode(name).get("temperature", default))


def fallback_of(name: str) -> str:
    return get_mode(name).get("fallback") or "AI 暂时不可用，请稍后重试。"


